/**
 * @file  params.h
 * @brief 走りを調整する値を、ここにまとめています。
 *        各自が走行の精度を上げるときは、まずこのファイルの値を変えます。
 */
#ifndef PARAMS_H
#define PARAMS_H

/* ===== 走行 ================================================================ */
#define RUN_SPEED_MPS    0.5f  /* 定常の速さ [m/s]。最初は低めにしてあります              */
#define RUN_ACCEL_MPS2   1.0f  /* 加速度 [m/s^2]                                           */
#define RUN_DECEL_MPS2   1.0f  /* ゴールのマーカーを見つけた後の減速度 [m/s^2]             */
#define START_DELAY_MS   1000  /* スイッチを押してから、動き出すまでの時間 [ms]            */
#define SKIP_MARKER_M    0.03f /* スタートのマーカーを読み飛ばす距離 [m]（マーカーの幅は19mm） */
#define STOP_HOLD_MS     500   /* 止まった後、ブレーキをかけ続ける時間 [ms]                */

/* ===== 安全のための停止 ==================================================== */
#define LOST_STOP_MS     300    /* ラインを見失ったまま、この時間が過ぎたら止まる [ms]                */
#define STALL_DUTY       0.10f  /* 車輪が回っていないことの確認：duty がこれより大きいのに、          */
#define STALL_SPEED_MPS  0.03f  /*   その車輪の速さがこれより小さい状態が、                           */
#define STALL_STOP_MS    500    /*   この時間続いたら止まる [ms]                                      */
#define REVERSE_SPEED_MPS 0.15f /* 逆に回っていることの確認：duty が STALL_DUTY より大きいのに、その車輪が */
#define REVERSE_STOP_MS  100    /*   後ろ向きにこの速さより速く回っている状態が、この時間続いたら止まる [ms]。
                                     エンコーダかモーターの向き（board.h）が逆のときに、ここで止まります  */
#define RUN_MAX_MS       120000 /* 走り始めてから、この時間が過ぎたら止まる [ms]                      */
#define DUTY_LIMIT       0.50f  /* モーターに出す duty の上限（1.0 = 100%）。最初は低めにしてあります。
                                   速さを上げて、duty がこの値に張り付くようになったら、大きくします   */
#define USE_WATCHDOG     1      /* 1 にすると、見張りのタイマー（ウォッチドッグ）を使います。
                                   1msの割り込みが長く止まったら、マイコンをリセットします。
                                   リセットされると、全部のピンが入力に戻るので、モーターが止まります。
                                   プログラムが途中で止まったまま、モーターが回り続けるのを防ぐためです。
                                   0 にすると使いません                                               */
#define WATCHDOG_MS      500    /* 見張りのタイマーの長さ [ms]。1msの割り込みが、この半分（250ms）より長く
                                   止まると、リセットされます                                         */

/* ===== 制御の定数 ==========================================================
 * モーターの duty を計算する式の定数は、モーターの担当の方のファイル
 * encoded_geared_motor/encoded_geared_motor.h にあります。
 *   K_SPEED_ERROR             : 速さの誤差にかける値 [V/(m/s)]
 *   K_YAW                     : 角速度の誤差にかける値 [V/(rad/s)]（USE_GYRO が1のとき）
 *   K_BACK_EMF_L、K_BACK_EMF_R : 逆起電力定数 [V/(rad/s)]。まっすぐ走らないときは、ここを左右で変えます
 *   MOTOR_x_FORWARD_CONST など : 静摩擦の補償の値
 *   SPEED_ERROR_PER_WHEEL     : 速さの誤差の計算のしかた（0 = 元の計算、1 = 仕様書 4.1.5 の式）
 */
#define OMEGA_GAIN       1.0f     /* ずれから決めた目標の角速度に掛ける倍率。ラインの上で左右に振れるときは、
                                     小さくします（例：0.7）。小さくしすぎると、きついカーブで曲がりきれなく
                                     なります。曲がりきれないときは、大きくします                         */
#define USE_GYRO         0        /* 1 にすると、ジャイロで読んだ角速度を、旋回の補正に使う。
                                     0 のときは、ジャイロを読まず、補正の量は0になります   */

/* ===== ラインセンサー ====================================================== */
#define CAL_MS           6000  /* キャリブレーションの時間の上限 [ms]。途中でスイッチ0を押すと、そこで終わります */
#define CAL_MIN_SPAN     100   /* 白と黒の差がこの値より小さいセンサーがあれば、失敗とする */
#define DISP_SCALE       0.32f /* 重みを掛けて足した値を、ずれ（-100〜+100）に直す倍率（先生のサンプルと同じ） */
#define WHITE_ON         60    /* 正規化した値（0〜100）がこれより大きければ「白」         */
#define WHITE_OFF        40    /* これより小さければ「黒」。間の値のときは、前の判定のまま */
#define LOST_NORM        30    /* ラインセンサー6個の正規化した値が、全部これより小さければ「ラインを見失った」 */

#endif /* PARAMS_H */
