static const uint8_t font_blank[8] = {0};
// ●万が一、フォントテーブルに存在しない文字（未登録の漢字など）が渡された時に
// 表示する 「全消灯（空白）のフォントデータ」。
// ●static const: メモリの静的領域に配置し、読み取り専用（書き換え不可）に設定。
// ●C言語の4つの主なメモリ領域
// プログラムが実行されるとき、メモリは主に次の4つの領域に分かれる。
// • テキスト領域（コード領域）: CPUが実行する命令（プログラムのコード）を置く場所。
// • 静的領域（データ領域）: グローバル変数や static 変数などを置く場所。
// • ヒープ領域: malloc などで、実行中に自由なサイズで確保・解放する場所。
// • スタック領域: 関数のローカル変数や引数を一時的に置く場所。

static inline const uint8_t* get_font_data(wchar_t code) {
// ●static inline
// このファイル限定（static）で、呼び出し元に埋め込んで高速化する（inline）
// という組み合わせ。
// ●const uint8_t* （戻り値の型）※読み取り専用
// uint8_t*: uint8_t(8bit整数型配列)先頭アドレスへのﾎﾟｲﾝﾀ型を返す。
// ※C言語では、配列名＝&配列名[0]、つまり配列の先頭要素へのアドレスを表す。
// ●wchar_t code （引数の型）
// 検索したい文字の Unicode コード（例: 'H' なら 0x0048）を受け取る。
// ●なぜ、static const wchar_t scroll_text[] = L" Hello Pico! こんにちは 12345 ";
// 実際の文字を指定したのに、文字コードを受け取ることが出来るのか？
// ➔C言語コンパイラにとって「文字」は、最初から「数値（文字コード）」そのものだから。
// 人間の見え方
// wchar_t c = L'H';
// C言語コンパイラ内部での実際の保持形式（Unicode）
// wchar_t c = 0x0048;  (10進数で 72 というただの整数データ)

    for (size_t i = 0; i < FONT_TABLE_SIZE; i++) {
    // ●font_table（配列）の 0 番目の文字から最後の文字
    // （FONT_TABLE_SIZE - 1）まで(i < FONT_TABLE_SIZEになっている、
    // かつ、配列は０始まりで１多いのでマイナス１)順番に、
    // Fontitem型構造体型配列font_tableを探す。
        if (font_table[i].code == code) return font_table[i].data;
    }
    return font_blank;
    // ●return font blank：
    // あらかじめ作っておいた全消灯データ font_blank（のアドレス）を返す。
    // これにより、プログラムがヌルポインタ（NULL）参照してクラッシュするのを防ぐ。
    // ●if (font_table[i].code == code):
    // テーブルの i 番目に登録されている文字コード（font_table[i].code）が、
    // 探している文字（code）と一致するか判定。
    // ●return font_table[i].data;:
    // 一致した場合、その文字の 8バイトのドット絵データ data を返して関数を終了。
    // なぜ data（配列）を返すだけでポインタ（uint8_t*）になるのか？
    // C言語は 「配列名は、式の中で自動的に先頭要素へのポインタ（アドレス）に変換
    // される」という文法ルールがある。
    // font_table[i].data と書くだけで、
    // 実質的に &font_table[i].data[0]（8バイト配列の0番目のアドレス）
    // を返していることになり、戻り値の型 const uint8_t* と一致する。
    // ➔君に説明して貰うと、ああそう言えばそんな文法事項あったなと思い出せるけれど、
    // その文法を利用して、この構造体や多重配列をひらめいたり、使用する方法を思い
    // 付けるのかと自問すると、とても出来ない、、、。それで少し落ち込む。
}

